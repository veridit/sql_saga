BEGIN;

CREATE SCHEMA pk_consistency;

-- A natural key value is bound to a single primary key value throughout history: add_unique_key adds a non-temporal
-- EXCLUDE guard per stable primary key column, in whichever order the two keys are added, also for a composite primary
-- key. There is no opt-out (1.14, hug mnntde): a natural key that could move between entities identifies nothing.
-- The SAVEPOINT expect_error blocks are refusals the test requires.

-- Scenario 1: PK added first, then NK
\echo --- Scenario 1: PK then NK ---
SAVEPOINT s1;

CREATE TABLE pk_consistency.pk_first (
    id int GENERATED BY DEFAULT AS IDENTITY,
    natural_key text,
    valid_range daterange,
    valid_from date,
    valid_until date
);
SELECT sql_saga.add_era('pk_consistency.pk_first','valid_range');
SELECT sql_saga.add_unique_key('pk_consistency.pk_first', ARRAY['id'], key_type => 'primary');
TABLE sql_saga.unique_keys;
\echo '--- Constraints after PK only ---'
\d pk_consistency.pk_first

SELECT sql_saga.add_unique_key('pk_consistency.pk_first', ARRAY['natural_key']);
TABLE sql_saga.unique_keys;
\echo '--- Constraints after NK ---'
\d pk_consistency.pk_first

ROLLBACK TO SAVEPOINT s1;


-- Scenario 2: NK added first, then PK
\echo
\echo --- Scenario 2: NK then PK ---
SAVEPOINT s2;
CREATE TABLE pk_consistency.nk_first (
    id int GENERATED BY DEFAULT AS IDENTITY,
    natural_key text,
    valid_range daterange,
    valid_from date,
    valid_until date
);
SELECT sql_saga.add_era('pk_consistency.nk_first','valid_range');
SELECT sql_saga.add_unique_key('pk_consistency.nk_first', ARRAY['natural_key']); -- Pending until a primary key exists
TABLE sql_saga.unique_keys;

\echo '--- Constraints after NK only ---'
\d pk_consistency.nk_first
SELECT sql_saga.add_unique_key('pk_consistency.nk_first', ARRAY['id'], key_type => 'primary'); -- This should retroactively apply the constraint
TABLE sql_saga.unique_keys;

\echo '--- Constraints after PK ---'
\d pk_consistency.nk_first

-- Verify it works
INSERT INTO pk_consistency.nk_first (id, natural_key, valid_from) VALUES (1, 'NK1', '2023-01-01');
SAVEPOINT expect_error;
INSERT INTO pk_consistency.nk_first (id, natural_key, valid_from) VALUES (2, 'NK1', '2023-02-01'); -- fails
ROLLBACK TO SAVEPOINT expect_error;

ROLLBACK TO SAVEPOINT s2;

-- Scenario 3: There is no opt-out (1.14). A natural key that could move between entities identifies nothing.
\echo
\echo --- Scenario 3: enforce_consistency_with_primary_key no longer exists ---
SAVEPOINT s3;
CREATE TABLE pk_consistency.opt_out (
    id int GENERATED BY DEFAULT AS IDENTITY,
    natural_key text,
    valid_range daterange,
    valid_from date,
    valid_until date
);
SELECT sql_saga.add_era('pk_consistency.opt_out','valid_range');
SELECT sql_saga.add_unique_key('pk_consistency.opt_out', ARRAY['id'], key_type => 'primary');
SAVEPOINT expect_error;
SELECT sql_saga.add_unique_key('pk_consistency.opt_out', ARRAY['natural_key'], enforce_consistency_with_primary_key => false); -- fails: no such parameter
ROLLBACK TO SAVEPOINT expect_error;
ROLLBACK TO SAVEPOINT s3;

-- Scenario 4: A composite primary key binds the natural key too, in either order (1.14). Before, 4a added the
-- natural key without any guard and 4b refused; the result depended on the order of two calls.
\echo
\echo --- Scenario 4a: Composite PK, then NK ---
SAVEPOINT s4a;
CREATE TABLE pk_consistency.composite_pk_a (
    org_id int,
    unit_id int,
    natural_key text,
    valid_range daterange,
    valid_from date,
    valid_until date
);
ALTER TABLE pk_consistency.composite_pk_a ADD PRIMARY KEY (org_id, unit_id, valid_range WITHOUT OVERLAPS);
SELECT sql_saga.add_era('pk_consistency.composite_pk_a','valid_range');
SELECT sql_saga.add_unique_key('pk_consistency.composite_pk_a', ARRAY['org_id', 'unit_id'], key_type => 'primary', unique_constraint => 'composite_pk_a_pkey');
SELECT sql_saga.add_unique_key('pk_consistency.composite_pk_a', ARRAY['natural_key']);
SELECT unique_key_name, key_type, pk_consistency_constraint_names FROM sql_saga.unique_keys WHERE table_name = 'composite_pk_a' ORDER BY unique_key_name;
SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint WHERE conrelid = 'pk_consistency.composite_pk_a'::regclass AND conname LIKE '%pk_consistency%' ORDER BY conname;
INSERT INTO pk_consistency.composite_pk_a (org_id, unit_id, natural_key, valid_from, valid_until) VALUES (1, 1, 'NK1', '2023-01-01', '2024-01-01');
INSERT INTO pk_consistency.composite_pk_a (org_id, unit_id, natural_key, valid_from, valid_until) VALUES (1, 1, 'NK1', '2024-01-01', '2025-01-01'); -- same entity later: ok
SAVEPOINT expect_error;
INSERT INTO pk_consistency.composite_pk_a (org_id, unit_id, natural_key, valid_from, valid_until) VALUES (1, 2, 'NK1', '2025-01-01', '2026-01-01'); -- fails: other unit
ROLLBACK TO SAVEPOINT expect_error;
SAVEPOINT expect_error;
INSERT INTO pk_consistency.composite_pk_a (org_id, unit_id, natural_key, valid_from, valid_until) VALUES (2, 1, 'NK1', '2025-01-01', '2026-01-01'); -- fails: other org
ROLLBACK TO SAVEPOINT expect_error;
SELECT sql_saga.check_integrity();
ROLLBACK TO SAVEPOINT s4a;

\echo
\echo --- Scenario 4b: NK, then composite PK ---
SAVEPOINT s4b;
CREATE TABLE pk_consistency.composite_pk_b (
    org_id int,
    unit_id int,
    natural_key text,
    valid_range daterange,
    valid_from date,
    valid_until date
);
SELECT sql_saga.add_era('pk_consistency.composite_pk_b','valid_range');
SELECT sql_saga.add_unique_key('pk_consistency.composite_pk_b', ARRAY['natural_key']);
SELECT sql_saga.add_unique_key('pk_consistency.composite_pk_b', ARRAY['org_id', 'unit_id'], key_type => 'primary');
SELECT unique_key_name, key_type, pk_consistency_constraint_names FROM sql_saga.unique_keys WHERE table_name = 'composite_pk_b' ORDER BY unique_key_name;
SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint WHERE conrelid = 'pk_consistency.composite_pk_b'::regclass AND conname LIKE '%pk_consistency%' ORDER BY conname;
INSERT INTO pk_consistency.composite_pk_b (org_id, unit_id, natural_key, valid_from, valid_until) VALUES (1, 1, 'NK1', '2023-01-01', '2024-01-01');
SAVEPOINT expect_error;
INSERT INTO pk_consistency.composite_pk_b (org_id, unit_id, natural_key, valid_from, valid_until) VALUES (1, 2, 'NK1', '2024-01-01', '2025-01-01'); -- fails: other unit
ROLLBACK TO SAVEPOINT expect_error;
SELECT sql_saga.check_integrity();
ROLLBACK TO SAVEPOINT s4b;

-- Scenario 4c: A natural key that contains every stable primary key column is bound by its own uniqueness: no guard.
\echo
\echo --- Scenario 4c: NK containing the whole stable PK needs no guard ---
SAVEPOINT s4c;
CREATE TABLE pk_consistency.nk_contains_pk (
    org_id int,
    unit_id int,
    valid_range daterange,
    valid_from date,
    valid_until date
);
SELECT sql_saga.add_era('pk_consistency.nk_contains_pk','valid_range');
SELECT sql_saga.add_unique_key('pk_consistency.nk_contains_pk', ARRAY['org_id'], key_type => 'primary');
SELECT sql_saga.add_unique_key('pk_consistency.nk_contains_pk', ARRAY['org_id', 'unit_id']);
SELECT unique_key_name, key_type, pk_consistency_constraint_names FROM sql_saga.unique_keys WHERE table_name = 'nk_contains_pk' ORDER BY unique_key_name;
SELECT sql_saga.check_integrity();
ROLLBACK TO SAVEPOINT s4c;

-- Scenario 4d: check_integrity reports a natural key whose guard is missing while a primary key exists.
\echo
\echo --- Scenario 4d: check_integrity reports an unguarded natural key ---
SAVEPOINT s4d;
CREATE TABLE pk_consistency.unguarded (
    id int GENERATED BY DEFAULT AS IDENTITY,
    natural_key text,
    valid_range daterange,
    valid_from date,
    valid_until date
);
SELECT sql_saga.add_era('pk_consistency.unguarded','valid_range');
SELECT sql_saga.add_unique_key('pk_consistency.unguarded', ARRAY['id'], key_type => 'primary');
SELECT sql_saga.add_unique_key('pk_consistency.unguarded', ARRAY['natural_key']);
-- The state an older release left behind for an opted-out key (bypassing the event triggers, as a restore would).
SET LOCAL session_replication_role = replica;
ALTER TABLE pk_consistency.unguarded DROP CONSTRAINT unguarded_natural_key_valid_pk_consistency_excl;
UPDATE sql_saga.unique_keys SET pk_consistency_constraint_names = NULL WHERE unique_key_name = 'unguarded_natural_key_valid';
RESET session_replication_role;
SAVEPOINT expect_error;
SELECT sql_saga.check_integrity(); -- fails
ROLLBACK TO SAVEPOINT expect_error;
ROLLBACK TO SAVEPOINT s4d;

-- Scenario 5: API Symmetry (Drop Key)
\echo
\echo --- Scenario 5a: Drop NK removes its consistency constraint ---
SAVEPOINT s5a;
CREATE TABLE pk_consistency.drop_nk (
    id int GENERATED BY DEFAULT AS IDENTITY,
    natural_key text,
    valid_range daterange,
    valid_from date,
