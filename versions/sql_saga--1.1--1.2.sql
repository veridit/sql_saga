    SELECT sql_saga.__internal_display_name(
        CASE WHEN schema_name = ANY (pg_catalog.current_schemas(true))
             THEN pg_catalog.quote_ident(object_name)
             ELSE pg_catalog.format('%I.%I', schema_name, object_name)
        END);
